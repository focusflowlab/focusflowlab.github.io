"""Write assets/tools/exam-topics.js (exam names, topic names and blueprint weights) from the plan pages.
The score tracker and error log use it. Re-run after a plan page's topics change:  python _tools/exam_topics.py"""
import json, pathlib, re

ROOT = pathlib.Path(__file__).resolve().parent.parent
LABEL = {"nclex": "NCLEX-RN", "nclex-pn": "NCLEX-PN", "teas": "ATI TEAS", "mcat": "MCAT", "usmle-step-1": "USMLE Step 1", "pance": "PANCE", "naplex": "NAPLEX", "dat": "DAT", "gre": "GRE", "gmat": "GMAT", "lsat": "LSAT", "cpa-far": "CPA FAR", "cpa-aud": "CPA AUD", "cpa-reg": "CPA REG"}
out = {}
for p in sorted((ROOT / "study-plan").glob("*/index.html")):
    h = p.read_text(encoding="utf-8")
    slug = p.parent.name
    start = h.index("EXAM_CONFIG")
    block = h[start:start + 6000]
    short = re.search(r'''"?shortName"?: ["']([^"']+)["']''', block).group(1)
    topics = re.findall(r'''\{"name": "([^"]+)", "weight": (\d+)\}''', block) or re.findall(r"""name: '([^']+)', weight: (\d+)""", block)
    # shortcut: weights are the plan pages' rough shares, not official numbers.
    out[slug] = {"name": LABEL.get(slug, short), "topics": [[n, int(w)] for n, w in topics]}
    assert out[slug]["topics"], slug
body = ",\n".join(f" {json.dumps(k)}: {json.dumps(v, ensure_ascii=False)}" for k, v in out.items())
js = "// Generated by _tools/exam_topics.py. Topic weights are rough planning shares, not official numbers.\nwindow.EXAM_TOPICS = {\n" + body + "\n};\n"
(ROOT / "assets/tools/exam-topics.js").write_text(js, encoding="utf-8", newline="\n")
print("wrote", len(out), "exams")
